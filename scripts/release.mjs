#!/usr/bin/env node
// Publish the version in package.json: git tag, GitHub release, then npm.
// npm receives the archive attached to the GitHub release, so both carry the
// same bytes. A new tag is only cut from a clean `main` equal to origin/main,
// after the host checks pass. Every step is skipped when already done, so a
// failed publish (an expired 2FA prompt, say) can simply be run again.
import { spawnSync } from 'node:child_process';
import { mkdtempSync, readdirSync, readFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const usage = `npm run release -- [--dry-run] [--tag DIST_TAG] [--notes-file FILE] [--otp CODE]

  --dry-run      run every check and build the archive; no tag, release or publish
  --tag          npm dist-tag; defaults to the prerelease id (0.2.0-beta.1 -> beta), or latest
  --notes-file   GitHub release notes; defaults to notes generated by GitHub
  --otp          one-time password, if npm asks for one`;

const options = { dryRun: false };
for (let i = 2; i < process.argv.length; i++) {
  const flag = process.argv[i];
  if (flag === '--help' || flag === '-h') { console.log(usage); process.exit(0); }
  if (flag === '--dry-run') { options.dryRun = true; continue; }
  const value = process.argv[++i];
  if (!value || value.startsWith('--')) throw new Error(`Missing value for ${flag}\n${usage}`);
  if (flag === '--tag') options.distTag = value;
  else if (flag === '--notes-file') options.notesFile = path.resolve(value);
  else if (flag === '--otp') options.otp = value;
  else throw new Error(`Unknown argument: ${flag}\n${usage}`);
}

// `npm run -s release` passes loglevel=silent down to child npm commands, which
// would then hide the errors and warnings this script reads.
const env = { ...process.env, npm_config_loglevel: 'notice' };
const capture = (command, args) => {
  const result = spawnSync(command, args, { cwd: root, encoding: 'utf8', env });
  if (result.error) throw result.error;
  return { status: result.status, stdout: result.stdout.trim(), stderr: result.stderr.trim() };
};
const output = (command, args) => {
  const result = capture(command, args);
  if (result.status !== 0) throw new Error(`${command} ${args.join(' ')} failed:\n${result.stderr || result.stdout}`);
  return result.stdout;
};
const run = (command, args) => {
  console.log(`\n$ ${command} ${args.join(' ')}`);
  const result = spawnSync(command, args, { cwd: root, stdio: 'inherit', env });
  if (result.error) throw result.error;
  if (result.status !== 0) throw new Error(`${command} ${args.join(' ')} exited with ${result.status}`);
};

const pkg = JSON.parse(readFileSync(path.join(root, 'package.json'), 'utf8'));
const { name, version } = pkg;
const gitTag = `v${version}`;
const prerelease = /^\d+\.\d+\.\d+-([0-9A-Za-z-]+)/.exec(version)?.[1];
const distTag = options.distTag ?? (prerelease && !/^\d+$/.test(prerelease) ? prerelease : prerelease ? 'next' : 'latest');
// `latest` is what a bare `npm install name` gets: never point it at a prerelease.
if (prerelease && distTag === 'latest') throw new Error(`${version} is a prerelease; publish it under another dist-tag than latest`);
console.log(`${name}@${version} → npm dist-tag "${distTag}", git tag ${gitTag}${options.dryRun ? ' (dry run)' : ''}`);

// Accounts first, before anything is built or pushed.
const npmUser = capture('npm', ['whoami']);
if (npmUser.status !== 0 && !options.dryRun) throw new Error('Not logged in to npm: run `npm login` first.');
if (capture('gh', ['auth', 'status']).status !== 0) throw new Error('The GitHub CLI is not logged in: run `gh auth login` first.');
const published = capture('npm', ['view', `${name}@${version}`, 'version']);
if (published.status === 0 && published.stdout === version) throw new Error(`${name}@${version} is already on npm; bump the version first.`);
if (published.status !== 0 && !/E404|404 Not Found/.test(published.stderr)) throw new Error(`Cannot query npm:\n${published.stderr}`);

const work = mkdtempSync(path.join(tmpdir(), 'rnskv-release-'));
const tagExists = capture('git', ['rev-parse', '--verify', '--quiet', `refs/tags/${gitTag}`]).status === 0 ||
  capture('git', ['ls-remote', '--exit-code', '--tags', 'origin', `refs/tags/${gitTag}`]).status === 0;
const releaseExists = capture('gh', ['release', 'view', gitTag]).status === 0;

if (tagExists && releaseExists) {
  // Already released on GitHub: publish its archive, built from the tag.
  console.log(`${gitTag} already has a GitHub release; downloading its archive.`);
  output('gh', ['release', 'download', gitTag, '--pattern', '*.tgz', '--dir', work]);
} else {
  if (tagExists) throw new Error(`${gitTag} exists without a GitHub release; create the release with its archive, then run this again.`);
  if (output('git', ['branch', '--show-current']) !== 'main') throw new Error('Cut a release from main.');
  if (output('git', ['status', '--porcelain'])) throw new Error('The working tree has uncommitted changes.');
  output('git', ['fetch', '--quiet', 'origin', 'main']);
  if (output('git', ['rev-parse', 'HEAD']) !== output('git', ['rev-parse', 'origin/main'])) throw new Error('main differs from origin/main: pull or push first.');
  // The host checks of CI, on the exact commit that gets tagged.
  for (const script of ['test', 'typecheck', 'test:package', 'build', 'check-package']) run('npm', ['run', script]);
  run('npm', ['pack', '--pack-destination', work]);
}

const archives = readdirSync(work).filter((file) => file.endsWith('.tgz'));
if (archives.length !== 1) throw new Error(`Expected one archive in ${work}, found ${archives.length}`);
const archive = path.join(work, archives[0]);
const packed = JSON.parse(output('tar', ['-xzOf', archive, 'package/package.json']));
if (packed.name !== name || packed.version !== version) throw new Error(`The archive holds ${packed.name}@${packed.version}, not ${name}@${version}`);
if (!packed.bin?.['skia-video-patch-canvas']) throw new Error('The archive has lost the skia-video-patch-canvas command.');

// npm silently rewrites or drops package.json fields it rejects (a `bin` path
// starting with ./ disappears, for instance): any such warning stops here.
const dry = capture('npm', ['publish', archive, '--dry-run', '--tag', distTag]);
if (dry.status !== 0 || /npm warn publish/i.test(dry.stderr)) throw new Error(`npm publish --dry-run is not clean:\n${dry.stderr}`);
console.log(`\n${archives[0]}: npm dry run clean.`);

if (options.dryRun) {
  console.log(`Dry run done; nothing was tagged, released or published. Archive: ${archive}`);
  process.exit(0);
}

if (!tagExists) {
  run('git', ['tag', '-a', gitTag, '-m', `${gitTag}`]);
  run('git', ['push', 'origin', gitTag]);
  const notes = options.notesFile ? ['--notes-file', options.notesFile] : ['--generate-notes'];
  run('gh', ['release', 'create', gitTag, archive, '--verify-tag', '--title', gitTag, ...notes,
    ...(prerelease ? ['--prerelease'] : [])]);
}

run('npm', ['publish', archive, '--tag', distTag, ...(options.otp ? ['--otp', options.otp] : [])]);
console.log(`\nPublished ${name}@${version}. dist-tags: ${output('npm', ['view', name, 'dist-tags', '--json'])}`);
console.log(`Install: npm install --save-exact ${name}@${distTag === 'latest' ? version : distTag}`);
